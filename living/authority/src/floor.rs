//! Floors: one module build hosts any world, its seed given at runtime, and a land too big for
//! one reducer is created in steps (docs/FLOORS.md, "Staged generation").
//!
//! **The seed.** A module built with a seed (`LIVING_SEED=<name>`, every lab and the island)
//! creates its world in `init`, as before. A floor module (`LIVING_SEED=none`) starts empty;
//! the admin's `create_floor(seed_json)` gives it its seed, kept in the private `floor_seed` row.
//!
//! **The budget.** SpacetimeDB 2.14.1 gives every reducer call 120 × 10⁹ fuel (WASM
//! instructions; `FunctionBudget::DEFAULT_BUDGET`, which standalone cannot raise), and a 4096 m
//! land needs about 2.8 of them. So a land larger than [`INLINE_MAX_M`] is generated by
//! `genesis_step`, a scheduled reducer that runs one bounded step per call and schedules the
//! next: [`living_rules::land::Gen`]'s steps (each under half a budget at 8192 m, measured with
//! `living/tools/land_fuel`), then hosting, the terrain chunks, lots and resources in batches,
//! then the people. The public `genesis` row shows how far it is; ticks start when it is done.
//!
//! **Where the work lives between steps.** Gigabytes of intermediate grids cannot go through
//! tables each step, so they stay in this instance's memory. SpacetimeDB does not promise module
//! memory survives between calls (reducers docs, "Global and Static Variables Are Undefined
//! Behavior"), so it is only a cache: the `genesis` row is the truth, the cache is used only when
//! it is this seed's and exactly as far as the row says, and otherwise generation restarts from
//! its first step. Generation is deterministic, so a restart rebuilds the same land; rows
//! already written (chunks, lots) are the same rows and are kept.

use crate::common;
use crate::island::Hosted;
use crate::seed::{self, Seed};
use crate::tables::*;
use living_rules::land::Gen;
use spacetimedb::{ReducerContext, ScheduleAt, Table};
use std::cell::RefCell;

/// Lands up to this side are created inside the one call (`init`, `create_floor`): the island
/// and the 2048 m megacity fit (about 60% of a budget at most). Larger lands are staged.
pub const INLINE_MAX_M: u32 = 2048;
/// Terrain chunks (16 × 16 tiles) inserted per step.
const CHUNKS_PER_STEP: usize = 16_384;
/// Lots (and the structures at their doors) inserted per step.
const LOTS_PER_STEP: usize = 8_192;
/// Rows of tiles searched for resources per step.
const RESOURCE_ROWS: u32 = 1024;

/// How far world creation is. One row, public: a client shows that the world is still being
/// made, and how far. `done` once the world ticks.
#[spacetimedb::table(accessor = genesis, public)]
#[derive(Clone)]
pub struct Genesis {
    #[primary_key]
    pub id: u8,
    /// Steps done, and the steps expected (the count grows once the city's wards are known).
    pub step: u32,
    pub steps: u32,
    /// What the next step does.
    pub label: String,
    /// Steps of generation and hosting done in this instance's memory (see the module notes).
    pub generated: u32,
    /// Durable progress: terrain chunks, lots, and resource rows done.
    pub chunks: u32,
    pub lots: u32,
    pub resource_rows: u32,
    /// Times generation started over because the instance's memory was lost.
    pub restarts: u32,
    pub started_ms: u64,
    pub updated_ms: u64,
    pub done: bool,
}

/// The seed a floor module was given at runtime (private: seeds hold authored sheets).
#[spacetimedb::table(accessor = floor_seed)]
pub struct FloorSeed {
    #[primary_key]
    pub id: u8,
    pub json: String,
}

#[spacetimedb::table(accessor = genesis_timer, scheduled(genesis_step))]
pub struct GenesisTimer {
    #[primary_key]
    #[auto_inc]
    pub scheduled_id: u64,
    pub scheduled_at: ScheduleAt,
}

/// What a staged creation holds in memory between steps.
struct Work {
    /// The seed text it was made from.
    seed: std::rc::Rc<str>,
    gen: Option<Gen>,
    hosted: Option<Hosted>,
    chunk_ids: Vec<u32>,
    /// Steps of generation and hosting done here (the row's `generated` must match).
    generated: u32,
}

thread_local! {
    static WORK: RefCell<Option<Work>> = const { RefCell::new(None) };
}

/// Give a floor module its world: parse and check the seed, keep it, and create the world (in
/// this call when small, else in steps). Admin only, once, on a module built without a seed.
#[spacetimedb::reducer]
pub fn create_floor(ctx: &ReducerContext, seed_json: String) -> Result<(), String> {
    let w = common::world(ctx);
    if ctx.sender() != w.admin {
        return Err("admin only".into());
    }
    if !seed::VALLEY.is_empty() {
        return Err("this module was built with a seed; build a floor module (LIVING_SEED=none) to give one at runtime".into());
    }
    if ctx.db.floor_seed().id().find(0).is_some() || ctx.db.genesis().id().find(0).is_some() {
        return Err("this floor already has its seed".into());
    }
    let s: Seed = serde_json::from_str(&seed_json).map_err(|e| format!("seed: {e}"))?;
    let laws = check(&s)?;
    if let Some(m) = s.map.as_ref().filter(|m| m.kind == "land") {
        crate::island::params_of(m)?;
    }
    ctx.db.floor_seed().insert(FloorSeed { id: 0, json: seed_json.clone() });
    seed::set_active(&seed_json);
    begin(ctx, &s, laws, common::now_ms(ctx))
}

/// What a seed says of its world's rules, checked before anything is written: its day length,
/// its laws overlay (composed over the shipped script, compiled and run on the install samples:
/// returned when it has one), and its `rules`, the world's own values of the script's laws, each
/// naming a law and of its kind (a number, or true or false).
pub fn check(s: &Seed) -> Result<Option<String>, String> {
    let day_ms = s.day_ms()?;
    let laws = s.script()?;
    let sc = living_rules::script::Scripts::with_day(laws.as_deref().unwrap_or(seed::SKILLS), day_ms).map_err(|e| format!("seed laws: {e}"))?;
    if laws.is_some() {
        sc.validate().map_err(|e| format!("seed laws: {e}"))?;
    }
    let over: Vec<(String, serde_json::Value)> = s.rules.iter().map(|(k, v)| (k.clone(), v.clone())).collect();
    sc.laws_with(&over).map_err(|e| format!("seed rules: {e}"))?;
    plan_kinds(s, &sc)?;
    Ok(laws)
}

/// A hand-authored plan names only resource and structure kinds, and stores only items, that the
/// world's tables have (its script with the seed's laws): a name that matches nothing is refused
/// here, before anything is written, instead of being left out when the world is populated.
fn plan_kinds(s: &Seed, sc: &living_rules::script::Scripts) -> Result<(), String> {
    let Some(m) = s.map.as_ref().filter(|m| m.kind == "land") else { return Ok(()) };
    let (_, params) = crate::island::params_of(m)?;
    let t = sc.tables();
    let has = |table: &str, name: &str| t.names(table).iter().any(|n| n == name);
    for p in &params.plans {
        let mut bad: std::collections::BTreeSet<String> = Default::default();
        for r in &p.resources {
            if !has("resources", &r.kind) {
                bad.insert(format!("resource `{}`", r.kind));
            }
        }
        for st in &p.structures {
            if !has("structures", &st.kind) {
                bad.insert(format!("structure `{}`", st.kind));
            }
        }
        let contents = p.structures.iter().flat_map(|st| st.contents.keys()).chain(p.lots.iter().flat_map(|l| l.contents.keys()));
        for item in contents {
            if !has("items", item) {
                bad.insert(format!("item `{item}`"));
            }
        }
        if !bad.is_empty() {
            let v: Vec<String> = bad.into_iter().collect();
            return Err(format!("map.params.plans: plan {} names kinds this world's tables do not have: {} (resources are {}; structures are {})", p.id, v.join(", "), t.names("resources").join(", "), t.names("structures").join(", ")));
        }
    }
    Ok(())
}

/// The world's day from its seed (`day_minutes`): the world row's `day_ms`, and the script
/// revision moved so every cache reads laws for that day.
fn set_day(ctx: &ReducerContext, s: &Seed) -> Result<(), String> {
    let day_ms = s.day_ms()?;
    let mut w = common::world(ctx);
    if w.day_ms == day_ms {
        return Ok(());
    }
    w.day_ms = day_ms;
    ctx.db.world().id().update(w);
    common::invalidate_world();
    common::invalidate_calendar();
    let mut k = common::clock(ctx);
    k.scripts_rev += 1;
    ctx.db.clock().id().update(k);
    common::invalidate_scripts_rev();
    log::info!("the world's day lasts {} real minutes", day_ms as f64 / 60_000.0);
    Ok(())
}

/// Keep the seed's `rules` as the world's own laws (`world_law`) and have every cache read them.
fn world_laws(ctx: &ReducerContext, s: &Seed) {
    for (name, value) in &s.rules {
        ctx.db.world_law().name().delete(name.clone());
        ctx.db.world_law().insert(WorldLaw { name: name.clone(), value: value.to_string() });
    }
    if s.rules.is_empty() {
        return;
    }
    // Written into the installed script too (`world_law_values()`), so the laws that read them
    // (`law(name)`) and every client that compiles the script have them; the seed check has
    // already run them (`check`).
    let mut k = common::clock(ctx);
    if let Some(mut row) = ctx.db.script().name().find("skills".to_string()) {
        row.source = crate::installed_source(&row.source, &crate::world_law_values(ctx));
        row.revision = row.revision.max(k.scripts_rev) + 1;
        k.scripts_rev = row.revision;
        ctx.db.script().name().update(row);
    } else {
        k.scripts_rev += 1;
    }
    ctx.db.clock().id().update(k);
    common::invalidate_scripts_rev();
}

/// Create the world from the active seed: in this call, or by scheduling the first step. First
/// its rules: its day, its laws overlay (installed as `install_script` installs a script) and its
/// own values of laws. `laws` is what [`check`] returned for this seed.
pub fn begin(ctx: &ReducerContext, s: &Seed, laws: Option<String>, now: u64) -> Result<(), String> {
    set_day(ctx, s)?;
    if let Some(source) = laws {
        crate::install_source(ctx, source)?;
        log::info!("the seed's laws are installed over the shipped script");
    }
    world_laws(ctx, s);
    let staged = s.map.as_ref().filter(|m| m.kind == "land").and_then(|m| crate::island::params_of(m).ok()).is_some_and(|(size, _)| size > INLINE_MAX_M);
    if !staged {
        seed::seed(ctx, now);
        crate::start_ticking(ctx);
        return Ok(());
    }
    log::info!("world creation is staged: a land too big for one reducer call");
    ctx.db.genesis().insert(Genesis { id: 0, step: 0, steps: 0, label: "starting".into(), generated: 0, chunks: 0, lots: 0, resource_rows: 0, restarts: 0, started_ms: now, updated_ms: now, done: false });
    schedule(ctx);
    Ok(())
}

fn schedule(ctx: &ReducerContext) {
    ctx.db.genesis_timer().insert(GenesisTimer { scheduled_id: 0, scheduled_at: ScheduleAt::Time(ctx.timestamp) });
}

/// Carry on a staged creation whose chain of steps stopped. A step is a one-shot schedule:
/// SpacetimeDB 2.14.1 deletes its row after the call whatever the outcome, and a step that
/// failed (returned an error or trapped) rolled back its own scheduling of the next, so nothing
/// runs again. This schedules the next step. Admin only; refused while a step is scheduled.
#[spacetimedb::reducer]
pub fn resume_genesis(ctx: &ReducerContext) -> Result<(), String> {
    if ctx.sender() != common::world(ctx).admin {
        return Err("admin only".into());
    }
    let g = ctx.db.genesis().id().find(0).ok_or("no staged creation here")?;
    if g.done {
        return Err("the world is already made".into());
    }
    if ctx.db.genesis_timer().iter().next().is_some() {
        return Err("a step is already scheduled".into());
    }
    log::info!("genesis: resumed at step {} ({})", g.step, g.label);
    schedule(ctx);
    Ok(())
}

/// Stop a staged creation between steps: the next step is unscheduled, as a failed step
/// leaves it (to free the server, or before a module update), and `resume_genesis` carries
/// on. Admin only.
#[spacetimedb::reducer]
pub fn stop_genesis(ctx: &ReducerContext) -> Result<(), String> {
    if ctx.sender() != common::world(ctx).admin {
        return Err("admin only".into());
    }
    let mut g = ctx.db.genesis().id().find(0).ok_or("no staged creation here")?;
    if g.done {
        return Err("the world is already made".into());
    }
    let timers: Vec<u64> = ctx.db.genesis_timer().iter().map(|t| t.scheduled_id).collect();
    if timers.is_empty() {
        return Err("no step is scheduled".into());
    }
    for id in timers {
        ctx.db.genesis_timer().scheduled_id().delete(id);
    }
    log::info!("genesis: stopped by the admin at step {}", g.step);
    g.label = format!("stopped by the admin before: {} (resume_genesis carries on)", g.label);
    g.updated_ms = common::now_ms(ctx);
    ctx.db.genesis().id().update(g);
    Ok(())
}

/// One step of a staged world creation (scheduled only). A step that fails keeps its reason
/// in the `genesis` row's label and schedules nothing; `resume_genesis` carries on.
#[spacetimedb::reducer]
pub fn genesis_step(ctx: &ReducerContext, _t: GenesisTimer) -> Result<(), String> {
    if ctx.sender() != ctx.database_identity() {
        return Err("genesis_step is scheduled only".into());
    }
    if let Err(e) = step(ctx) {
        log::error!("genesis: step failed: {e}");
        if let Some(mut g) = ctx.db.genesis().id().find(0) {
            g.label = format!("stopped: {e} (resume_genesis carries on)");
            g.updated_ms = common::now_ms(ctx);
            ctx.db.genesis().id().update(g);
        }
    }
    Ok(())
}

/// The step itself. Its errors come before it writes anything.
fn step(ctx: &ReducerContext) -> Result<(), String> {
    let Some(mut g) = ctx.db.genesis().id().find(0) else { return Ok(()) };
    if g.done {
        return Ok(());
    }
    seed::load(ctx);
    let text = seed::active();
    let s: Seed = serde_json::from_str(&text).map_err(|e| format!("seed: {e}"))?;
    let m = s.map.as_ref().ok_or("a staged world needs a land map")?;
    let (size, params) = crate::island::params_of(m)?;
    let now = common::now_ms(ctx);
    let done = WORK.with(|cell| -> Result<bool, String> {
        let mut cell = cell.borrow_mut();
        let fresh = !matches!(&*cell, Some(w) if w.seed == text && w.generated == g.generated);
        if fresh {
            if g.generated > 0 {
                g.restarts += 1;
                log::warn!("genesis: this instance lost the land at step {} of generation; generating again from the start", g.generated);
            }
            *cell = Some(Work { seed: text.clone(), gen: Some(Gen::new(s.seed, size, params.clone())), hosted: None, chunk_ids: Vec::new(), generated: 0 });
            g.generated = 0;
        }
        let w = cell.as_mut().expect("work");
        let label;
        if let Some(gen) = w.gen.as_mut().filter(|gen| !gen.is_done()) {
            label = gen.label();
            let _t = spacetimedb::log_stopwatch::LogStopwatch::new("genesis.generate");
            gen.step();
            (w.generated, g.generated) = (w.generated + 1, g.generated + 1);
        } else if w.hosted.is_none() {
            label = "hosting: buildings into the tiles, digests".into();
            let _t = spacetimedb::log_stopwatch::LogStopwatch::new("genesis.host");
            let land = w.gen.take().expect("generated land").into_land();
            let h = crate::island::host(s.seed, m, &land, &params)?;
            drop(land);
            w.chunk_ids = h.map.chunks().collect();
            w.hosted = Some(h);
            (w.generated, g.generated) = (w.generated + 1, g.generated + 1);
        } else if (g.chunks as usize) < w.chunk_ids.len() {
            let h = w.hosted.as_ref().expect("hosted");
            let (a, b) = (g.chunks as usize, (g.chunks as usize + CHUNKS_PER_STEP).min(w.chunk_ids.len()));
            label = format!("terrain chunks {a}..{b} of {}", w.chunk_ids.len());
            let _t = spacetimedb::log_stopwatch::LogStopwatch::new("genesis.chunks");
            for &id in &w.chunk_ids[a..b] {
                // A restart after a lost instance writes the same rows again: keep the first.
                if ctx.db.terrain_chunk().id().find(id).is_none() {
                    ctx.db.terrain_chunk().insert(TerrainChunk { id, tiles: h.map.chunk_bytes(id) });
                }
            }
            g.chunks = b as u32;
        } else if (g.lots as usize) < w.hosted.as_ref().expect("hosted").lots.len() {
            let h = w.hosted.as_ref().expect("hosted");
            let (a, b) = (g.lots as usize, (g.lots as usize + LOTS_PER_STEP).min(h.lots.len()));
            label = format!("lots {a}..{b} of {}", h.lots.len());
            let _t = spacetimedb::log_stopwatch::LogStopwatch::new("genesis.lots");
            if ctx.db.lot().id().find(a as u32).is_none() {
                crate::island::build_lots(ctx, h, a..b, now);
            }
            g.lots = b as u32;
        } else if g.resource_rows < size {
            let h = w.hosted.as_ref().expect("hosted");
            let (a, b) = (g.resource_rows, (g.resource_rows + RESOURCE_ROWS).min(size));
            label = format!("resources, rows {a}..{b}");
            let _t = spacetimedb::log_stopwatch::LogStopwatch::new("genesis.resources");
            seed::spawn_resources_rows(ctx, &h.map, &s, a..b, now);
            g.resource_rows = b;
        } else {
            label = "people, animals and the settlements' life".into();
            let _t = spacetimedb::log_stopwatch::LogStopwatch::new("genesis.populate");
            let h = w.hosted.take().expect("hosted");
            seed::world_row(ctx, &s, &h.map);
            ctx.db.land().insert(h.info.clone());
            seed::populate(ctx, &s, &h.map, Some(&h), None, Vec::new(), now);
            *cell = None;
            log::info!("genesis: the world is made ({} steps, {} s)", g.step + 1, now.saturating_sub(g.started_ms) / 1000);
            g.label = label;
            return Ok(true);
        }
        g.label = label;
        Ok(false)
    })?;
    g.step += 1;
    g.steps = expected(&g, size);
    g.updated_ms = now;
    g.done = done;
    if done {
        g.steps = g.step;
        g.label = "done".into();
    }
    ctx.db.genesis().id().update(g);
    if done {
        crate::start_ticking(ctx);
    } else {
        schedule(ctx);
    }
    Ok(())
}

/// The steps a creation is expected to take, from what this instance knows so far.
fn expected(g: &Genesis, size: u32) -> u32 {
    WORK.with(|cell| {
        let cell = cell.borrow();
        let Some(w) = cell.as_ref() else { return g.step };
        let gen = w.gen.as_ref().map_or(g.generated, |gen| gen.steps().max(g.generated));
        let chunks = (size as usize / 16).pow(2).div_ceil(CHUNKS_PER_STEP) as u32;
        let lots = w.hosted.as_ref().map_or(1, |h| h.lots.len().div_ceil(LOTS_PER_STEP) as u32);
        gen + 1 + chunks + lots + size.div_ceil(RESOURCE_ROWS) + 1
    })
}

/// The runtime seed's row, if this floor was given one.
pub fn seed_row(ctx: &ReducerContext) -> Option<FloorSeed> {
    ctx.db.floor_seed().id().find(0)
}
