"""Convert the ordered Blender journal to a standalone replay script."""
import json
from pathlib import Path

root = Path(__file__).resolve().parent
header = """# Generated by make_replay.py. Run blender -b --factory-startup -P replay.py
import os
from pathlib import Path
ROOT = Path(os.environ.get("CHAR_LIVE_OUTPUT", Path(__file__).resolve().parent))
ROOT.mkdir(parents=True, exist_ok=True)
"""
blocks = [json.loads(line) for line in (root / "session.jsonl").read_text().splitlines()]
(root / "replay.py").write_text(header + "".join(
    f"\n# {row['timestamp']}  {row['stage']}\n{row['code'].rstrip()}\n" for row in blocks))
