"""Convert the ordered Blender journal to a standalone replay script."""
import json
from pathlib import Path

root = Path(__file__).resolve().parent
header = """# Generated by make_replay.py. Run blender -b --factory-startup -P replay.py
import os
from pathlib import Path
ROOT = Path(os.environ.get("CHAR_LIVE_OUTPUT", Path(__file__).resolve().parent))
ROOT.mkdir(parents=True, exist_ok=True)
"""
blocks = [json.loads(line) for line in (root / "session.jsonl").read_text().splitlines()]
# Two earlier submissions intentionally remain in the journal. Continue only
# through their observed failures, so an unrelated replay error still aborts.
expected = {
    "restart-material-audit": ("RuntimeError", "Render Result"),
    "clothing": ("ZeroDivisionError", "divide by zero"),
}
parts = [header]
for row in blocks:
    code = row["code"].rstrip()
    if row["stage"] in expected:
        kind, message = expected[row["stage"]]
        code = ("try:\n" + "\n".join("    " + line for line in code.splitlines())
                + f"\nexcept {kind} as exc:\n    if {message!r} not in str(exc):\n        raise")
    parts.append(f"\n# {row['timestamp']}  {row['stage']}\n{code}\n")
(root / "replay.py").write_text("".join(parts))
